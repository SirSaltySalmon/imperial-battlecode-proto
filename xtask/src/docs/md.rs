//! Markdown helpers shared by the generated pages.

/// One table cell: a single line, with pipes escaped.
pub fn cell(s: &str) -> String {
    s.split('\n')
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

/// A GitHub-flavoured Markdown table, followed by a blank line.
pub fn table(header: &[&str], rows: &[Vec<String>]) -> String {
    let line = |cells: Vec<String>| format!("| {} |\n", cells.join(" | "));
    let mut out = line(header.iter().map(|h| cell(h)).collect());
    out += &line(header.iter().map(|_| "---".to_string()).collect());
    for row in rows {
        out += &line(row.iter().map(|c| cell(c)).collect());
    }
    out.push('\n');
    out
}

pub fn code(s: &str) -> String {
    format!("`{s}`")
}

/// The banner every generated page starts with.
pub fn banner(sources: &str) -> String {
    format!(
        "<!-- Generated by `cargo xtask docs` from {sources}. Do not edit: change the source and \
         regenerate. CI runs `cargo xtask docs --check`. -->\n\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cells_are_one_line_and_pipes_are_escaped() {
        assert_eq!(cell("a | b\n  c\n"), "a \\| b c");
        assert_eq!(
            table(&["x", "y"], &[vec!["1".into(), "2".into()]]),
            "| x | y |\n| --- | --- |\n| 1 | 2 |\n\n"
        );
    }
}
