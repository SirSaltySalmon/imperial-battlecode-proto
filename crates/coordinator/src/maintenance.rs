//! Operator commands that work on a data directory, safe to run while the server is up:
//!
//! - `ibc-coordinator backup DIR`: a consistent snapshot of the database (`VACUUM INTO`) to
//!   `DIR/coordinator.sqlite` and an incremental copy of the blobs to `DIR/blobs/`. Blobs are content
//!   addressed and never change, so a blob already in the backup is skipped and repeated backups into the
//!   same `DIR` only copy what is new.
//! - `ibc-coordinator prune-replays --older-than DAYS [--kinds unranked] [--dry-run]`: delete replay
//!   blobs of finished matches of those kinds. A replay is a pure function of (patch, map, bots, seed), all
//!   of which stay in the database, so it can be regenerated by re-running the match on the same patch.
//!   Results, ratings and the match list are untouched; the pruned replay's download answers 404.

use crate::model::Class;
use rusqlite::{params_from_iter, Connection, OpenFlags};
use std::path::{Path, PathBuf};
use std::time::Duration;

const DB_FILE: &str = "coordinator.sqlite";
const BLOBS: &str = "blobs";

#[derive(Debug, Default, PartialEq, Eq)]
pub struct BackupReport {
    pub database_bytes: u64,
    pub blobs_copied: u64,
    pub blobs_present: u64,
    pub bytes_copied: u64,
}

/// Snapshot `data` into `dest`. The database first: every blob it references was written before its row,
/// so the blob copy that follows holds all of them.
pub fn backup(data: &Path, dest: &Path) -> anyhow::Result<BackupReport> {
    std::fs::create_dir_all(dest)?;
    let tmp = dest.join(format!("{DB_FILE}.tmp"));
    let _ = std::fs::remove_file(&tmp);
    read_database(data, |conn| {
        conn.execute("VACUUM INTO ?1", [tmp.to_string_lossy()])?;
        Ok(())
    })?;
    let final_db = dest.join(DB_FILE);
    std::fs::rename(&tmp, &final_db)?;
    let mut report = BackupReport {
        database_bytes: std::fs::metadata(&final_db)?.len(),
        ..BackupReport::default()
    };
    copy_blobs(&data.join(BLOBS), &dest.join(BLOBS), &mut report)?;
    Ok(report)
}

/// Run `f` on a read-only connection to the data directory's database.
///
/// In WAL mode even a reader may create `coordinator.sqlite-wal` / `-shm` when the server is not running.
/// Run from root's cron against a service that runs as its own user, those files would then belong to root
/// and the service could not open its database; so afterwards they are given the database file's owner.
fn read_database<T>(
    data: &Path,
    f: impl FnOnce(&Connection) -> anyhow::Result<T>,
) -> anyhow::Result<T> {
    let db = data.join(DB_FILE);
    if !db.is_file() {
        anyhow::bail!(
            "{} not found: is {} a data directory?",
            db.display(),
            data.display()
        );
    }
    let conn = Connection::open_with_flags(&db, OpenFlags::SQLITE_OPEN_READ_ONLY)?;
    conn.busy_timeout(Duration::from_secs(30))?;
    let out = f(&conn);
    drop(conn);
    keep_owner(&db)?;
    out
}

#[cfg(unix)]
fn keep_owner(db: &Path) -> anyhow::Result<()> {
    use std::os::unix::fs::MetadataExt;
    let owner = std::fs::metadata(db)?;
    for suffix in ["-wal", "-shm"] {
        let side = PathBuf::from(format!("{}{suffix}", db.display()));
        if let Ok(meta) = std::fs::metadata(&side) {
            if (meta.uid(), meta.gid()) != (owner.uid(), owner.gid()) {
                std::os::unix::fs::chown(&side, Some(owner.uid()), Some(owner.gid()))?;
            }
        }
    }
    Ok(())
}

#[cfg(not(unix))]
fn keep_owner(_db: &Path) -> anyhow::Result<()> {
    Ok(())
}

/// `<root>/ab/cdef…` files; `tmp/` (writes in progress) is skipped.
fn copy_blobs(from: &Path, to: &Path, report: &mut BackupReport) -> anyhow::Result<()> {
    if !from.is_dir() {
        return Ok(());
    }
    for shard in std::fs::read_dir(from)? {
        let shard = shard?;
        let name = shard.file_name();
        if name == "tmp" || !shard.path().is_dir() {
            continue;
        }
        let dest_shard = to.join(&name);
        for blob in std::fs::read_dir(shard.path())? {
            let blob = blob?;
            let target = dest_shard.join(blob.file_name());
            let size = blob.metadata()?.len();
            if target.metadata().is_ok_and(|m| m.len() == size) {
                report.blobs_present += 1;
                continue;
            }
            std::fs::create_dir_all(&dest_shard)?;
            let partial = target.with_extension("partial");
            std::fs::copy(blob.path(), &partial)?;
            std::fs::rename(&partial, &target)?;
            report.blobs_copied += 1;
            report.bytes_copied += size;
        }
    }
    Ok(())
}

#[derive(Debug, Default, PartialEq, Eq)]
pub struct PruneReport {
    /// Distinct replay blobs eligible for deletion.
    pub replays: u64,
    /// Of those, the ones whose file existed and was (or, with a dry run, would be) deleted.
    pub deleted: u64,
    pub bytes: u64,
}

/// Replays of series games whose class (the job's, or for a verification run the verified job's) is one
/// of `kinds`, finished before `before_ms`, and not shared with any match that is kept: a game of another
/// kind that reused the job, or another job with the same replay hash.
///
/// Only jobs that belong to series games qualify. A finished job is a result cache keyed by its inputs,
/// and enqueueing the same inputs again returns it instead of playing it; for series games that cannot
/// happen in practice, because their seeds derive from the random 64-bit series id, but stand-alone jobs
/// (`POST /v1/admin/jobs`, benchmarks) are re-submitted with the same seeds on purpose, and a pruned replay
/// would then be handed out as a cache hit that has no replay. Their replays are kept.
const PRUNABLE_SQL: &str = "
WITH owner AS (
  SELECT j.id, j.replay_sha256 AS sha, j.finished_at, j.state,
         COALESCE((SELECT o.class FROM jobs o WHERE o.id = j.verifies), j.class) AS class,
         COALESCE(j.verifies, j.id) AS game_job
  FROM jobs j WHERE j.replay_sha256 IS NOT NULL),
prunable AS (
  SELECT o.id, o.sha FROM owner o
  WHERE o.state = 'done' AND o.finished_at < ?1 AND o.class IN (KINDS)
    AND EXISTS (SELECT 1 FROM games g WHERE g.job_id = o.game_job)
    AND NOT EXISTS (SELECT 1 FROM games g JOIN series s ON s.id = g.series_id
                    WHERE g.job_id = o.game_job AND s.kind NOT IN (NAMES)))
SELECT DISTINCT p.sha FROM prunable p
WHERE NOT EXISTS (SELECT 1 FROM owner k WHERE k.sha = p.sha AND k.id NOT IN (SELECT id FROM prunable))
ORDER BY p.sha";

/// The replay hashes `prune_replays` would delete.
pub fn prunable_replays(
    conn: &Connection,
    kinds: &[Class],
    before_ms: i64,
) -> anyhow::Result<Vec<String>> {
    if kinds.is_empty() {
        anyhow::bail!("no kinds to prune");
    }
    let holes = |from: usize| {
        (0..kinds.len())
            .map(|i| format!("?{}", from + i))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let sql = PRUNABLE_SQL
        .replace("KINDS", &holes(2))
        .replace("NAMES", &holes(2 + kinds.len()));
    let mut values: Vec<rusqlite::types::Value> = vec![before_ms.into()];
    values.extend(kinds.iter().map(|k| (*k as i64).into()));
    values.extend(kinds.iter().map(|k| k.name().to_string().into()));
    let mut st = conn.prepare(&sql)?;
    let rows = st.query_map(params_from_iter(values), |r| r.get::<_, String>(0))?;
    Ok(rows.collect::<rusqlite::Result<_>>()?)
}

pub fn prune_replays(
    data: &Path,
    kinds: &[Class],
    before_ms: i64,
    dry_run: bool,
) -> anyhow::Result<PruneReport> {
    let shas = read_database(data, |conn| prunable_replays(conn, kinds, before_ms))?;
    let mut report = PruneReport {
        replays: shas.len() as u64,
        ..PruneReport::default()
    };
    for sha in &shas {
        let Some(path) = blob_path(data, sha) else {
            continue;
        };
        let Ok(meta) = std::fs::metadata(&path) else {
            continue;
        };
        if !dry_run {
            std::fs::remove_file(&path)?;
        }
        report.deleted += 1;
        report.bytes += meta.len();
    }
    Ok(report)
}

fn blob_path(data: &Path, sha: &str) -> Option<PathBuf> {
    crate::util::is_sha256(sha).then(|| data.join(BLOBS).join(&sha[..2]).join(&sha[2..]))
}

#[derive(clap::Parser)]
#[command(
    name = "ibc-coordinator",
    about = "Maintenance of a coordinator data directory"
)]
enum Maintenance {
    /// Snapshot the database and copy new blobs into DIR (safe while the server runs)
    Backup {
        /// Backup directory: DIR/coordinator.sqlite and DIR/blobs/
        dir: PathBuf,
        /// Data directory of the coordinator
        #[arg(long, env = "IBC_DATA")]
        data: PathBuf,
    },
    /// Delete replays of old matches of some kinds (they can be regenerated from the database)
    PruneReplays {
        /// Only matches finished more than this many days ago
        #[arg(long)]
        older_than: u32,
        /// Comma-separated kinds: tournament, ranked, unranked, bench
        #[arg(long, default_value = "unranked")]
        kinds: String,
        /// Report what would be deleted, delete nothing
        #[arg(long)]
        dry_run: bool,
        /// Data directory of the coordinator
        #[arg(long, env = "IBC_DATA")]
        data: PathBuf,
    },
}

/// The maintenance commands, if `args` (program name first) names one; `None` otherwise (run the server).
pub fn from_args(args: Vec<std::ffi::OsString>) -> Option<anyhow::Result<()>> {
    let command = args.get(1)?.to_str()?;
    if !["backup", "prune-replays"].contains(&command) {
        return None;
    }
    let parsed = <Maintenance as clap::Parser>::parse_from(args);
    Some(run(parsed))
}

fn run(command: Maintenance) -> anyhow::Result<()> {
    match command {
        Maintenance::Backup { dir, data } => {
            let r = backup(&data, &dir)?;
            println!(
                "backup {}: database {} bytes; blobs: {} copied ({} bytes), {} already there",
                dir.display(),
                r.database_bytes,
                r.blobs_copied,
                r.bytes_copied,
                r.blobs_present
            );
        }
        Maintenance::PruneReplays {
            older_than,
            kinds,
            dry_run,
            data,
        } => {
            let kinds = parse_kinds(&kinds)?;
            let before = crate::util::now_ms() - i64::from(older_than) * 86_400_000;
            let r = prune_replays(&data, &kinds, before, dry_run)?;
            let verb = if dry_run { "would delete" } else { "deleted" };
            println!(
                "{} eligible replays; {verb} {} files, {} bytes",
                r.replays, r.deleted, r.bytes
            );
        }
    }
    Ok(())
}

/// `unranked,bench` -> classes; unknown names are an error.
pub fn parse_kinds(s: &str) -> anyhow::Result<Vec<Class>> {
    s.split(',')
        .map(str::trim)
        .filter(|k| !k.is_empty())
        .map(|k| {
            Class::parse(k).ok_or_else(|| {
                anyhow::anyhow!("unknown kind {k:?} (tournament, ranked, unranked, bench)")
            })
        })
        .collect()
}

